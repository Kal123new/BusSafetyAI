"""Lightweight serverless API. Camera inference runs in the visitor's browser."""
import os
from dataclasses import replace
from sqlalchemy.engine import make_url

os.environ['SAFESENSE_MODE'] = 'production'
os.environ['SAFESENSE_DATA_DIR'] = '/tmp/safesense'
os.environ['YOLO_MODEL_PATH'] = ''
os.environ['SAFESENSE_REQUIRE_MODEL'] = 'false'
raw_url = os.environ.get('DATABASE_URL', '')
if not raw_url:
    raise RuntimeError('Configure DATABASE_URL in hosting environment settings')
url = make_url(raw_url)
if url.get_backend_name() not in {'postgres', 'postgresql'}:
    raise RuntimeError('Hosted application requires persistent PostgreSQL')
if url.query.get('sslmode') not in {'require', 'verify-ca', 'verify-full'}:
    raise RuntimeError('Hosted database connection must require TLS')
os.environ['DATABASE_URL'] = url.set(drivername='postgresql+psycopg').render_as_string(hide_password=False)

from backend.config import Settings
from backend.app import create_app

# No background threads in request-driven hosting. Daily trips are generated by
# the authenticated ensure-daily endpoint when users open or refresh the app.
app = create_app(replace(Settings.from_env(), model_path='', require_model=False), background_scheduler=False)
